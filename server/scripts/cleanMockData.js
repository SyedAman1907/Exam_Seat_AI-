require('dotenv').config({ path: require('path').join(__dirname, '../.env') });
const mongoose = require('mongoose');
const Student = require('../models/Student');
const Exam = require('../models/Exam');
const Allocation = require('../models/Allocation');
const Classroom = require('../models/Classroom');
const seedDatabase = require('../utils/seedDatabase');

async function cleanMockData() {
  const mongoUri = process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017/examseat_ai';
  console.log('Connecting to MongoDB:', mongoUri);
  await mongoose.connect(mongoUri);

  console.log('--- PURGING ALL MOCK AND DEMONSTRATION DATA ---');

  // Delete mock students generated by initial tests/seed
  const studentDeleteResult = await Student.deleteMany({
    $or: [
      { name: { $regex: /Kumar$/i } },
      { name: { $regex: /TEST/i } },
      { registrationNumber: { $regex: /^24091A05\d{2}$/ } },
      { registrationNumber: { $regex: /^24091A06\d{2}$/ } },
      { registrationNumber: { $regex: /^24091A07\d{2}$/ } },
    ],
  });
  console.log(`Deleted ${studentDeleteResult.deletedCount} mock students.`);

  // Delete mock allocations
  const allocDeleteResult = await Allocation.deleteMany({});
  console.log(`Deleted ${allocDeleteResult.deletedCount} old test/demo allocations.`);

  // Delete mock exams
  const examDeleteResult = await Exam.deleteMany({});
  console.log(`Deleted ${examDeleteResult.deletedCount} old test/demo exams.`);

  // Remove old single classroom A-101
  const oldClassrooms = await Classroom.deleteMany({ roomNumber: { $regex: /^A-101/i } });
  console.log(`Deleted ${oldClassrooms.deletedCount} legacy classroom records.`);

  console.log('\n--- SEEDING 51 ET BLOCK CLASSROOMS (2010 - 2060) ---');
  await seedDatabase();

  const classroomCount = await Classroom.countDocuments({ block: 'ET BLOCK' });
  const finalStudentCount = await Student.countDocuments();
  const finalExamCount = await Exam.countDocuments();
  const finalAllocCount = await Allocation.countDocuments();

  console.log('\n--- VERIFICATION OF REAL-DATA STATE ---');
  console.log(`Active ET BLOCK Classrooms: ${classroomCount} (Expected: 51)`);
  console.log(`Current Real Students in Database: ${finalStudentCount} (Expected: 0 if no faculty upload)`);
  console.log(`Current Real Exams in Database: ${finalExamCount} (Expected: 0)`);
  console.log(`Current Real Allocations in Database: ${finalAllocCount} (Expected: 0)`);

  await mongoose.disconnect();
  console.log('\nDatabase cleanup complete. Ready for real faculty PDF uploads!');
}

cleanMockData().catch((err) => {
  console.error('Cleanup failed:', err);
  process.exit(1);
});
